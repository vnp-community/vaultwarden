/// Collect compliance evidence for the specified standard (or all).
async fn collect_evidence(standard: &str, conn: &DbConn) -> Value {
    // Common stats
    let total_users = User::count_all(conn).await;
    let users_with_2fa = TwoFactor::count_distinct_users(conn).await;
    let tfa_rate = if total_users > 0 {
        (users_with_2fa as f64 / total_users as f64 * 100.0).round() as i64
    } else {
        0
    };
    let completed_erasures = ErasureLog::count_completed(conn).await;

    let base = json!({
        "generatedAt": Utc::now(),
        "region": CONFIG.data_residency_region(),
        "totalUsers": total_users,
        "twoFactorRate": tfa_rate,
        "completedGdprErasures": completed_erasures,
        "vaultwardenVersion": env!("CARGO_PKG_VERSION"),
    });

    match standard {
        "pci-dss" => json!({
            "standard": "PCI-DSS v4.0",
            "evidence": {
                "requirement_2_2": "Security headers enforced via SecurityHeadersFairing",
                "requirement_6_3": format!("2FA rate: {}%", tfa_rate),
                "requirement_10_3": "Audit events stored in `event` table with immutable timestamps",
                "dataStats": base,
            }
        }),
        "soc2" => json!({
            "standard": "SOC 2 Type II",
            "evidence": {
                "CC6_1": format!("Access controls: 2FA rate {}%", tfa_rate),
                "CC6_6": "Trusted proxy validation via get_real_ip()",
                "CC7_2": "Emergency access with multi-tier notifications",
                "A1_1": format!("Data region: {}", CONFIG.data_residency_region()),
                "dataStats": base,
            }
        }),
        "iso27001" => json!({
            "standard": "ISO 27001:2022",
            "evidence": {
                "A_5_23": "Information security in use of cloud services",
                "A_8_5": format!("Privileged access rate (2FA): {}%", tfa_rate),
                "A_8_24": "Cryptographic controls: AES-256-GCM, RSA-2048",
                "A_8_32": "Change log: see /admin panel event log",
                "dataStats": base,
            }
        }),
        "gdpr" => json!({
            "standard": "GDPR",
            "evidence": {
                "article_17": format!("Right to erasure: {} completed erasures", completed_erasures),
                "article_20": "Data portability: GET /api/accounts/export-data",
                "article_32": "Technical security: TLS, PBKDF2/Argon2, E2E encryption",
                "dataStats": base,
            }
        }),
        _ => json!({
            "standard": "all",
            "evidence": {
                "pciDss": collect_pci_summary(tfa_rate),
                "soc2": collect_soc2_summary(tfa_rate),
                "iso27001": collect_iso27001_summary(tfa_rate),
                "gdpr": collect_gdpr_summary(completed_erasures),
                "dataStats": base,
            }
        }),
    }
}

fn collect_pci_summary(tfa_rate: i64) -> Value {
    json!({ "twoFactorRate": tfa_rate, "encryptionAlgorithm": "AES-256-GCM" })
}

fn collect_soc2_summary(tfa_rate: i64) -> Value {
    json!({ "twoFactorRate": tfa_rate, "trustedProxyValidation": true })
}

fn collect_iso27001_summary(tfa_rate: i64) -> Value {
    json!({ "privilegedAccessRate": tfa_rate, "keyManagement": "RSA-2048 + AES-256-GCM" })
}

fn collect_gdpr_summary(completed_erasures: i64) -> Value {
    json!({ "completedErasures": completed_erasures, "portabilityEndpoint": "/api/accounts/export-data" })
}

