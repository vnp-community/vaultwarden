/// `GET /api/compliance/evidence?standard=pci-dss|soc2|iso27001|gdpr`
///
/// Returns structured compliance evidence for the requested standard.
/// Requires admin authentication and `COMPLIANCE_REPORT_ENABLED=true`.
#[get("/api/compliance/evidence?<standard>")]
pub async fn get_compliance_evidence(
    _admin: AdminToken,
    standard: Option<String>,
    conn: DbConn,
) -> JsonResult {
    if !CONFIG.compliance_report_enabled() {
        err!("Compliance reports are disabled. Set COMPLIANCE_REPORT_ENABLED=true.");
    }

    let std_name = standard.as_deref().unwrap_or("all");
    let evidence = collect_evidence(std_name, &conn).await;

    Ok(Json(evidence))
}

/// `GET /api/compliance/evidence/export?format=json|csv`
///
/// Exports compliance evidence. JSON by default; CSV when format=csv.
/// TASK-001-012: CSV generation via generate_csv_report().
#[get("/api/compliance/evidence/export?<format>&<standard>")]
pub async fn export_compliance_report(
    _admin: AdminToken,
    format: Option<String>,
    standard: Option<String>,
    conn: DbConn,
) -> ApiResult<(rocket::http::ContentType, String)> {
    if !CONFIG.compliance_report_enabled() {
        err!("Compliance reports are disabled.");
    }

    let std_name = standard.as_deref().unwrap_or("all");
    let evidence = collect_evidence(std_name, &conn).await;

    match format.as_deref() {
        Some("csv") => Ok((
            rocket::http::ContentType::new("text", "csv"),
            generate_csv_report(&evidence),
        )),
        _ => Ok((
            rocket::http::ContentType::JSON,
            serde_json::to_string_pretty(&evidence).unwrap_or_default(),
        )),
    }
}

