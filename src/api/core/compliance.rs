// TASK-001-008: Background job — execute_scheduled_erasures
// Called from main.rs scheduler (wired in TASK-001-013).
// ═══════════════════════════════════════════════════════════════════════════════

/// Daily background job: finds users past their `pii_erasure_scheduled_at`
/// deadline and anonymises their PII fields (GDPR right to erasure).
///
/// Anonymisation strategy:
/// - `email`  → `erased-{uuid}@erased.invalid`
/// - `name`   → `[ERASED]`
/// - Other PII (password_hint, api_key) → cleared
/// - Marks `pii_erased_at` in users table
/// - Marks corresponding ErasureLog entry as completed
pub async fn execute_scheduled_erasures(pool: crate::db::DbPool) {
    let conn = match pool.get().await {
        Ok(c) => c,
        Err(e) => {
            error!("execute_scheduled_erasures: DB pool error: {e:?}");
            return;
        }
    };

    let pending = ErasureLog::find_pending_due(&conn).await;
    info!("[GDPR] Erasure job running: {} pending deletions", pending.len());

    for mut log in pending {
        // Find the user — they may have already been hard-deleted
        let user_opt = User::find_by_uuid(
            &crate::db::models::UserId::from(log.user_uuid.clone()),
            &conn,
        )
        .await;

        if let Some(mut user) = user_opt {
            // Anonymise PII
            user.email = format!("erased-{}@erased.invalid", user.uuid);
            user.name = "[ERASED]".to_string();
            user.password_hint = None;
            user.api_key = None;
            user.avatar_color = None;
            user.pii_erased_at = Some(Utc::now().naive_utc());

            if let Err(e) = user.save(&conn).await {
                error!("[GDPR] Failed to anonymise user {}: {e:?}", log.user_uuid);
                continue;
            }

            info!("[GDPR] Anonymised PII for user {}", log.user_uuid);
        } else {
            // User already deleted — still mark the log complete
            warn!("[GDPR] User {} not found; marking erasure log complete anyway", log.user_uuid);
        }

        // Mark erasure log complete
        log.mark_completed();
        if let Err(e) = log.save(&conn).await {
            error!("[GDPR] Failed to update erasure log {}: {e:?}", log.uuid);
        }
    }
}
