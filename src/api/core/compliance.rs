/// `GET /api/accounts/export-data`
///
/// Returns all personal data held for the authenticated user as JSON.
/// Complies with GDPR Article 20 (right to data portability).
#[get("/api/accounts/export-data")]
pub async fn export_user_data(headers: Headers, conn: DbConn) -> JsonResult {
    let user = &headers.user;
    let user_uuid = &user.uuid;

    // Collect ciphers (async to_json)
    let raw_ciphers = Cipher::find_owned_by_user(user_uuid, &conn).await;
    let mut ciphers: Vec<Value> = Vec::with_capacity(raw_ciphers.len());
    for c in &raw_ciphers {
        ciphers.push(c.to_json(&headers.host, user_uuid, None, crate::api::core::ciphers::CipherSyncType::User, &conn).await?);
    }

    // Collect sends
    let sends: Vec<Value> = Send::find_by_user(user_uuid, &conn)
        .await
        .iter()
        .map(|s| s.to_json())
        .collect();

    // Collect 2FA config (types only — no secrets)
    let two_factors: Vec<Value> = TwoFactor::find_by_user(user_uuid, &conn)
        .await
        .iter()
        .map(|t| {
            json!({
                "type": t.atype,
                "enabled": t.enabled,
            })
        })
        .collect();

    Ok(Json(json!({
        "object": "gdprDataExport",
        "profile": {
            "id": user.uuid,
            "name": user.name,
            "email": user.email,
            "createdAt": user.created_at,
            "updatedAt": user.updated_at,
            "verifiedAt": user.verified_at,
        },
        "ciphers": ciphers,
        "sends": sends,
        "twoFactorProviders": two_factors,
        "exportedAt": Utc::now(),
    })))
}

