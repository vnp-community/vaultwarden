/// RFC 9116 security.txt
/// Served at `GET /.well-known/security.txt` — no auth required.
#[get("/.well-known/security.txt")]
pub fn security_txt() -> (rocket::http::ContentType, String) {
    let contact = CONFIG.security_txt_contact();
    let expires = CONFIG.security_txt_expires();

    let content = if contact.is_empty() {
        // Minimal valid security.txt when not configured
        format!(
            "# security.txt generated by Vaultwarden (SOL-001)\n\
             # Configure SECURITY_TXT_CONTACT and SECURITY_TXT_EXPIRES environment variables.\n\
             Expires: {}\n",
            // Provide a sane default 1 year ahead
            (Utc::now() + TimeDelta::try_days(365).unwrap())
                .format("%Y-%m-%dT%H:%M:%SZ")
        )
    } else {
        let expires_str = if expires.is_empty() {
            (Utc::now() + TimeDelta::try_days(365).unwrap())
                .format("%Y-%m-%dT%H:%M:%SZ")
                .to_string()
        } else {
            expires.clone()
        };
        format!(
            "Contact: {contact}\n\
             Expires: {expires_str}\n\
             Preferred-Languages: en\n\
             # Generated by Vaultwarden (SOL-001 Enterprise Compliance Framework)\n"
        )
    };

    (rocket::http::ContentType::Plain, content)
}

