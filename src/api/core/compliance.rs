/// `POST /api/accounts/delete-gdpr`
///
/// Initiates the GDPR erasure pipeline for the authenticated user:
/// 1. Revokes all active sessions (invalidates security stamp).
/// 2. Schedules PII erasure date = now + GDPR_ERASURE_DELAY_DAYS.
/// 3. Creates an ErasureLog entry in the append-only audit chain.
/// 4. Marks user as pending erasure in the users table.
#[post("/api/accounts/delete-gdpr")]
pub async fn delete_account_gdpr(headers: Headers, conn: DbConn) -> EmptyResult {
    let mut user = headers.user;
    let ip = headers.ip.ip.to_string();

    // Guard: disallow if already scheduled
    if user.pii_erasure_scheduled_at.is_some() {
        err!("GDPR erasure is already scheduled for this account");
    }

    let delay_days = CONFIG.gdpr_erasure_delay_days() as i64;
    let scheduled_at = (Utc::now() + TimeDelta::try_days(delay_days).unwrap()).naive_utc();

    // Revoke all sessions by rotating the security stamp
    user.reset_security_stamp();
    user.pii_erasure_scheduled_at = Some(scheduled_at);
    user.save(&conn).await?;

    // Append to erasure audit chain
    let prev_hash = ErasureLog::get_last_hash(&conn).await;
    let log = ErasureLog::new(&user.uuid.to_string(), scheduled_at, &ip, &prev_hash);
    log.save(&conn).await?;

    info!("[GDPR] Erasure scheduled for user {} at {scheduled_at}", user.uuid);
    Ok(())
}

