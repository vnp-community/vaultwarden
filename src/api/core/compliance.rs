// TASK-001-012: CSV report generation (report.rs inline)
// ═══════════════════════════════════════════════════════════════════════════════

/// Generate a CSV compliance report from evidence JSON.
/// Flattens the top-level `evidence` object into key,value rows.
pub fn generate_csv_report(evidence: &Value) -> String {
    let mut out = String::from("field,value\n");

    if let Some(obj) = evidence.as_object() {
        flatten_into_csv(obj, "", &mut out);
    }

    out
}

fn flatten_into_csv(obj: &serde_json::Map<String, Value>, prefix: &str, out: &mut String) {
    for (key, value) in obj {
        let full_key = if prefix.is_empty() {
            key.clone()
        } else {
            format!("{prefix}.{key}")
        };

        match value {
            Value::Object(inner) => flatten_into_csv(inner, &full_key, out),
            Value::String(s) => out.push_str(&format!("{full_key},{}\n", csv_escape(s))),
            other => out.push_str(&format!("{full_key},{}\n", csv_escape(&other.to_string()))),
        }
    }
}

fn csv_escape(s: &str) -> String {
    if s.contains(',') || s.contains('"') || s.contains('\n') {
        format!("\"{}\"", s.replace('"', "\"\""))
    } else {
        s.to_string()
    }
}

